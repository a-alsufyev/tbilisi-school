function transliterate(value: string): string {
  return [...value]
    .map((char) => {
      const lower = char.toLowerCase();
      return RU[lower] ?? GE[char] ?? char;
    })
    .join("");
}

export function slugFromEnglishName(name: string): string {
  const slug = transliterate(name)
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return isSafeSchoolIdentifier(slug) ? slug : "";
}

export function suggestSlug(names: readonly string[]): string {
  for (const name of names) {
    const slug = slugFromEnglishName(name);
    if (slug) return slug;
  }
  return "school";
}
